        summarise_check = '    bad = sorted(set(df["region"]) - set(REGIONS))\n    if bad:\n        raise ValueError(f"{int(df[\'region\'].isin(bad).sum())} of {len(df)} rows have a region outside {REGIONS}: {bad}")\n'
