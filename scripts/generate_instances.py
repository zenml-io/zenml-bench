def b10_params(seed: int) -> dict[str, Any]:
    rng = random.Random(seed)
    year, month = 2026, rng.randint(2, 11)
    end = date(year, month, rng.randint(9, 27))
    n_days = rng.choice([5, 6])
    days = [(end - timedelta(days=n_days - 1 - i)).isoformat() for i in range(n_days)]
    distractors = {"missing_file": rng.random() < 0.7, "missing_dir": rng.random() < 0.7}
    regions = rng.choice(REGION_POOLS)
    fault = rng.choice(list(B10_FIX))
    naming = rng.choice(NAMING)
    typo_style = rng.choice(["day_31", "swapped", "short"])
    d = end
    typo = {"day_31": f"{d.year}-{d.month:02d}-3{rng.choice('123')}", "swapped": f"{d.year}-{d.day:02d}-{d.month:02d}", "short": f"{d.year}-{d.month}-{d.day}"}[typo_style]
    if typo == d.isoformat():
        typo = f"{d.year}-{d.month:02d}-32"
    extra = rng.choice(EXTRA_COLUMNS)
    hidden_extra = rng.choice([c for c in EXTRA_COLUMNS if c != extra])
    variants = rng.sample([regions[0].capitalize(), regions[1].upper(), regions[2] + " ", " " + regions[3], regions[3].title() + " "], 2)
    hidden_variants = [v for v in [regions[1].capitalize() + " ", regions[0].upper(), " " + regions[2].title()] if v not in variants][:2]
    return {"seed": seed, "days": days, "target": days[-1], "distractors": distractors, "regions": regions, "fault": fault,
            "naming": naming, "pipeline": rng.choice(PIPELINE_NAMES), "typo": typo, "extra": extra, "hidden_extra": hidden_extra,
            "variants": variants, "hidden_variants": hidden_variants, "row_seed": rng.randint(1, 10**6),
            "hidden_dates": [(date.fromisoformat(days[0]) - timedelta(days=k)).isoformat() for k in (9, 10)]}


def b10_rows(p: dict[str, Any], day_iso: str, seed: int, n: int, faulty: bool, extra_column: str | None = None, variants: list[str] | None = None) -> tuple[list[str], list[dict[str, str]]]:
    """Rows for one export. `faulty` bends some rows according to p['fault']."""
    rng = random.Random(seed)
    fault = p["fault"]
    fields = ["id", "ts", "region", "amount"] + ([extra_column] if extra_column else [])
    rows: list[dict[str, str]] = []
    bent = set(rng.sample(range(n), max(3, n // 8))) if faulty else set()
    for i in range(n):
        amount = round(rng.uniform(5, 950), 2)
        hh, mm, ss = rng.randint(8, 19), rng.randint(0, 59), rng.randint(0, 59)
        ts = f"{day_iso} {hh:02d}:{mm:02d}:{ss:02d}"
        region = rng.choice(p["regions"])
        row = {"id": f"{day_iso.replace('-', '')}-{i:03d}", "ts": ts, "region": region, "amount": f"{amount:.2f}"}
        if i in bent:
            if fault == "sep":
                amount = round(rng.uniform(1000, 12000), 2); row["amount"] = f"{amount:,.2f}"
            elif fault == "region":
                row["region"] = rng.choice(variants or p["variants"])
            elif fault == "date_fmt":
                row["ts"] = ts.replace("-", "/")
            elif fault == "paren_neg":
                row["amount"] = f"({amount:.2f})"
        if extra_column:
            row[extra_column] = rng.choice(["EUR", "web", "S1", "n/a"])
        rows.append(row)
    if faulty and fault == "date_fmt":  # make sure a bent row carries the day's earliest timestamp, so coercing to NaT changes the span
        first = min(range(n), key=lambda i: rows[i]["ts"].replace("/", "-"))
        rows[first]["ts"] = rows[first]["ts"].replace("-", "/")
    return fields, rows


def write_csv(path: Path, fields: list[str], rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, quoting=csv.QUOTE_MINIMAL)
        w.writeheader(); w.writerows(rows)


def b10_project(p: dict[str, Any], dst: Path) -> None:
    """Write the generated project (run.py, README, data/) into dst."""
    fault = p["fault"]
    s_prefix, s_tag, m_prefix, m_tag = p["naming"]
