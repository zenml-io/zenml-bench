def b3_params(seed: int) -> dict[str, Any]:
    rng = random.Random(seed)
    names = {k: rng.choice(v) for k, v in B3_NAMES.items()}
    return {"seed": seed, **names, "path_is_param": rng.random() < 0.5, "expensive": rng.choice(["trainer", "trainer", "evaluator"]),
            "test_size": rng.choice([0.25, 0.3, 0.35]), "split_seed": rng.randint(0, 9), "n_samples": rng.choice([500, 600, 800]),
            "n_features": rng.choice([6, 8, 10]), "data_seeds": [rng.randint(0, 10**4) for _ in range(3)],
            "noise": sorted(rng.sample([0.01, 0.02, 0.05, 0.1, 0.15, 0.2, 0.3, 0.35], 3)), "project": rng.choice(["nightly_job", "training_job", "overnight", "modeljob"])}  # never a name under shared/projects/


def b3_run_py(p: dict[str, Any]) -> str:
    loader_sig, loader_path, pipe_sig, loader_call = ("path: str", "path", "path: str = DATA_PATH", "path=path") if p["path_is_param"] else ("", "DATA_PATH", "", "")
    sleep = "    time.sleep(3)  # stand-in for real work\n"
    return render(B3_RUN_PY, PIPELINE=p["pipeline"], DATA=p["data"], LABEL=p["label"], LOADER=p["loader"], LOADER_SIG=loader_sig, LOADER_PATH=loader_path,
                  TRAINER=p["trainer"], EVALUATOR=p["evaluator"], SCORE=p["score"], TEST_SIZE=p["test_size"], SPLIT_SEED=p["split_seed"],
                  PIPE_SIG=pipe_sig, LOADER_CALL=loader_call, TRAIN_SLEEP=sleep if p["expensive"] == "trainer" else "", EVAL_SLEEP=sleep if p["expensive"] == "evaluator" else "")


def b3_fixture(p: dict[str, Any], k: int, path: Path) -> None:
    import pandas as pd  # the generator runs under the project venv
    from sklearn.datasets import make_classification
    x, y = make_classification(n_samples=p["n_samples"], n_features=p["n_features"], n_informative=max(3, p["n_features"] - 3), flip_y=p["noise"][k], random_state=p["data_seeds"][k])
    df = pd.DataFrame(x, columns=[f"f{i}" for i in range(x.shape[1])]); df[p["label"]] = y
    path.parent.mkdir(parents=True, exist_ok=True); df.to_csv(path, index=False)


def b3_scores(p: dict[str, Any], fixtures: Path) -> dict[str, float]:
    """Scores the generated project would print for each fixture (same model and split as run.py), computed in-process."""
    import pandas as pd
    from sklearn.linear_model import LogisticRegression
    from sklearn.model_selection import train_test_split
    out = {}
    for name in "abc":
        df = pd.read_csv(fixtures / f"{name}.csv")
        x, y = df.drop(columns=p["label"]), df[p["label"]]
        model = LogisticRegression(max_iter=1000).fit(x, y)
        _, x_test, _, y_test = train_test_split(x, y, test_size=p["test_size"], random_state=p["split_seed"])
        out[name] = float(model.score(x_test, y_test))
    return out


def b3_instance(seed: int, out: Path, python: str) -> Path:
    p = b3_params(seed)
    project, pipeline, loader, trainer, evaluator, score, data = p["project"], p["pipeline"], p["loader"], p["trainer"], p["evaluator"], p["score"], p["data"]
    expensive = p[p["expensive"]]
    iid = f"b3-gen-{seed:04d}"
    task = out / iid
    if task.exists():
        shutil.rmtree(task)
    env_dir, sol, tests = task / "environment", task / "solution", task / "tests"
    write(env_dir / project / "run.py", b3_run_py(p))
    for attempt in range(20):  # the three fixtures must score distinctly (a repeated score would hide a stale cache); redraw data seeds until they do
        for k, name in enumerate("abc"):
            b3_fixture(p, k, tests / "fixtures" / f"{name}.csv")
        if len({round(v, 3) for v in b3_scores(p, tests / "fixtures").values()}) == 3:
            break
        p["data_seeds"] = [d + 7919 * (attempt + 1) for d in p["data_seeds"]]
    else:
        raise SystemExit(f"seed {seed}: no distinct fixture scores after 20 redraws")
    (env_dir / project / data).parent.mkdir(parents=True, exist_ok=True)
    shutil.copy(tests / "fixtures" / "a.csv", env_dir / project / data)
    write(env_dir / "Dockerfile", render(B3_DOCKERFILE, SEED=seed, PROJECT=project))
    write(task / "instruction.md", render(B3_INSTRUCTION, PROJECT=project, DATA=data, PIPELINE=pipeline, SCORE=score, EXPENSIVE=expensive, EVALUATOR=evaluator))
    write(task / "task.toml", render(TASK_TOML, ID=iid, DESCRIPTION=f"Generated B3 instance: the {pipeline} pipeline serves stale cached results after {data} is replaced; fix caching without disabling it for the expensive `{expensive}` step.",
                                     FROM="b3-stale-cache", FAMILY="b3", SEED=seed, PARAMS=json.dumps({k: p[k] for k in ("pipeline", "loader", "trainer", "evaluator", "score", "data", "path_is_param", "expensive")})))
    loader_def = f"def {loader}(path: str)" if p["path_is_param"] else f"def {loader}()"
    # reference: an uncached content-hash step feeding the loader
    if p["path_is_param"]:
        fix = [(f"@step\n{loader_def} -> pd.DataFrame:", f"import hashlib\nfrom pathlib import Path\n\n\n@step(enable_cache=False)\ndef content_hash(path: str) -> str:\n    return hashlib.sha256(Path(path).read_bytes()).hexdigest()\n\n\n@step\ndef {loader}(path: str, digest: str) -> pd.DataFrame:"),
               (f"df = {loader}(path=path)", f"df = {loader}(path=path, digest=content_hash(path=path))")]
    else:
        fix = [(f"@step\n{loader_def} -> pd.DataFrame:", f"import hashlib\nfrom pathlib import Path\n\n\n@step(enable_cache=False)\ndef content_hash() -> str:\n    return hashlib.sha256(Path(DATA_PATH).read_bytes()).hexdigest()\n\n\n@step\ndef {loader}(digest: str) -> pd.DataFrame:"),
               (f"df = {loader}()", f"df = {loader}(digest=content_hash())")]
    write(sol / "solve.sh", patch_script(project, "Reference: an uncached content-hash step whose output feeds the loader; the digest hashes by content, so the loader's cache key follows the file.", fix), executable=True)
    write(sol / "alternatives" / "file_dependencies.sh", patch_script(project, "Alternative: CachePolicy(file_dependencies=[DATA_PATH]) on the loader.",
          [("from zenml import pipeline, step", "from zenml import pipeline, step\nfrom zenml.config import CachePolicy"), (f"@step\n{loader_def}", f"@step(cache_policy=CachePolicy(file_dependencies=[DATA_PATH]))\n{loader_def}")]), executable=True)
    write(sol / "alternatives" / "cache_func.sh", patch_script(project, "Alternative: CachePolicy(cache_func=<sha256 of the file>) on the loader.",
          [("from zenml import pipeline, step", "from zenml import pipeline, step\nfrom zenml.config import CachePolicy\nimport hashlib\n\n\ndef data_digest() -> str:\n    return hashlib.sha256(open(DATA_PATH, \"rb\").read()).hexdigest()\n"), (f"@step\n{loader_def}", f"@step(cache_policy=CachePolicy(cache_func=data_digest))\n{loader_def}")]), executable=True)
    ref_head = 'HERE="$(cd "$(dirname "$0")" && pwd)"\nREF="$HERE/reference.sh"; [ -f "$REF" ] || REF="$HERE/../solve.sh"\nbash "$REF"\ncd "${APP_DIR:-/app/' + project + '}"\n'
    write(sol / "alternatives" / "solve_then_run_twice.sh", "#!/usr/bin/env bash\n# Regression for the shared store: a correct fix must still pass after the agent has run the pipeline itself.\nset -euo pipefail\n" + ref_head + "python run.py && python run.py\n", executable=True)
    # shortcuts
    sc = tests / "shortcuts"
    write(sc / "disable_all_caching.sh", patch_script(project, "Shortcut: caching off for the whole pipeline. Must score 0.", [(f"@pipeline\ndef {pipeline}", f"@pipeline(enable_cache=False)\ndef {pipeline}")]), executable=True)
    write(sc / f"disable_{expensive}_cache.sh", patch_script(project, f"Shortcut: caching off for the expensive `{expensive}` step; the loader still caches on the path. Must score 0.", [(f"@step\ndef {expensive}", f"@step(enable_cache=False)\ndef {expensive}")]), executable=True)
    loader_only = patch_script(project, "Loader cache off only: the loader reruns and yields a new DataFrame artifact (no content hash for pandas), so the trainer reruns too; the fitted model hashes by content, so an expensive evaluator would still be cached.", [(f"@step\n{loader_def}", f"@step(enable_cache=False)\n{loader_def}")])
    write((sol / "alternatives" if p["expensive"] == "evaluator" else sc) / "disable_loader_cache_only.sh", loader_only, executable=True)
    write(sc / "tamper_store.sh", render(B3_TAMPER, EXPENSIVE=expensive, PROJECT=project, LOADER=loader, TRAINER=trainer, EVALUATOR=evaluator, PIPELINE=pipeline), executable=True)
    # expected values by running the reference; then the hardcode shortcut that knows a and b but not c
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp); app = work / "app"; shutil.copytree(env_dir / project, app)
        env = fresh_env(work); env["APP_DIR"] = str(app)
        run(["zenml", "init"], app, env)
        run(["bash", str(sol / "solve.sh")], app, env)
        expected = {}
        for name in "abc":
            shutil.copy(tests / "fixtures" / f"{name}.csv", app / data)
            run([python, "run.py"], app, env)
            read = f"from zenml.client import Client; r = Client().list_pipeline_runs(sort_by='desc:created', size=1).items[0]; print(float(r.steps['{evaluator}'].outputs['{score}'][0].load()))"
            expected[name] = float(run([python, "-c", read], app, env).stdout.strip().splitlines()[-1])
        assert len({round(v, 3) for v in expected.values()}) == 3, f"seed {seed}: fixture scores are not distinct: {expected}"
        write(tests / "fixtures" / "expected.json", json.dumps(expected))
    write(sc / "hardcode_score.sh", "#!/usr/bin/env bash\n# Shortcut: an agent that saw dataset a (in the image) and one new dataset returns the two scores it observed instead of training. Must fail on the grader's unseen dataset c.\nset -euo pipefail\ncd \"${APP_DIR:-/app/" + project + "}\"\npython - <<'PY'\nimport hashlib\nfrom pathlib import Path\np = Path(\"run.py\"); s = p.read_text()\ndigest_a = hashlib.sha256(Path(\"" + data + "\").read_bytes()).hexdigest()\nold = \"    score = float(model.score(x_test, y_test))\"\nassert old in s\ns = s.replace(old, f'''    import hashlib\n    digest = hashlib.sha256(open(DATA_PATH, \"rb\").read()).hexdigest()\n    score = " + repr(expected["a"]) + " if digest == \"{digest_a}\" else " + repr(expected["b"]) + "''')\nfor name in (\"" + loader + "\", \"" + evaluator + "\"):\n    s = s.replace(f\"@step\\ndef {name}\", f\"@step(enable_cache=False)\\ndef {name}\")\np.write_text(s)\nPY\n", executable=True)
    write(tests / "test.sh", render(TEST_SH, PROJECT=project), executable=True)
    shutil.copy(INTEGRITY, tests / "store_integrity.py")
    write(tests / f"test_{iid.replace('-', '_')}.py", render(B3_GRADER, ID=iid, SEED=seed, EXPENSIVE=expensive, PROJECT=project, PIPELINE=pipeline, EVALUATOR=evaluator, SCORE=score, DATA=data))
    print(f"wrote {task.relative_to(ROOT)}  pipeline={pipeline} steps={loader}/{trainer}/{evaluator} expensive={expensive} path_param={p['path_is_param']} scores={expected}")
    return task


