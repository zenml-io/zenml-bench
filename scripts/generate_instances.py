def render(template: str, **kw: Any) -> str:
    """Replace «KEY» markers; braces stay literal so templates can hold Python and JSON."""
    out = template
    for k, v in kw.items():
        out = out.replace(f"«{k}»", str(v))
    assert "«" not in out, f"unrendered marker in template: {out[out.index('«'):][:60]}"
    return out


def write(path: Path, text: str, executable: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    if executable:
        path.chmod(0o755)


def fresh_env(work: Path) -> dict[str, str]:
    return {**os.environ, "ZENML_CONFIG_PATH": str(work / "zenml"), "ZENML_ANALYTICS_OPT_IN": "false", "ZENML_LOGGING_VERBOSITY": "ERROR"}


def run(cmd: list[str], cwd: Path, env: dict[str, str], check: bool = True) -> subprocess.CompletedProcess:
    proc = subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True, timeout=900)
    if check and proc.returncode != 0:
        raise SystemExit(f"command failed: {' '.join(cmd)}\n{proc.stdout[-2000:]}\n{proc.stderr[-3000:]}")
    return proc


