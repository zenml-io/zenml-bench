def b10_history(p: dict[str, Any]) -> tuple[str, dict[str, tuple[str, dict[str, str]]]]:
    """setup_store.sh body and the SEEDED map the grader checks."""
    s_prefix, s_tag, m_prefix, m_tag = p["naming"]
    ok = {"load": "completed", "parse": "completed", "summarise": "completed", "write_report": "completed"}
    lines, seeded = [], {}
    dir_made = False
    for i, d in enumerate(p["days"]):
        name = f"{s_prefix}-{d}"
        if p["distractors"]["missing_file"] and i == 0:
            lines.append(f"run --date {d} --trigger {s_tag}   # no data/{d}.csv was delivered: FileNotFoundError in `load`")
            seeded[name] = ("failed", {"load": "failed"})
            continue
        if p["distractors"]["missing_dir"] and not dir_made and d != p["target"]:
            lines.append(f"run --date {d} --trigger {s_tag}   # reports/ did not exist yet: FileNotFoundError in `write_report`")
            lines.append("mkdir -p reports                            # ...which someone fixed by hand the same day")
            seeded[name] = ("failed", {"load": "completed", "parse": "completed", "summarise": "completed", "write_report": "failed"})
            dir_made = True
            continue
        if not dir_made:
            lines.append("mkdir -p reports"); dir_made = True
        if d == p["target"]:
            fail_step = B10_FAIL_STEP[p["fault"]]
            steps = {"load": "completed", "parse": "failed"} if fail_step == "parse" else {"load": "completed", "parse": "completed", "summarise": "failed"}
            lines.append(f"run --date {d} --trigger {s_tag}   # the real fault ({p['fault']}): ValueError in `{fail_step}`")
            seeded[name] = ("failed", steps)
        else:
            lines.append(f"run --date {d} --trigger {s_tag}   # completed")
            seeded[name] = ("completed", ok)
    lines.append(f"run --date {p['typo']}                       # someone's typo, started by hand after the failure: FileNotFoundError in `load`")
    seeded[f"{m_prefix}-{p['typo']}"] = ("failed", {"load": "failed"})
    return "\n".join(lines), seeded


def patch_script(project: str, comment: str, edits: list[tuple[str, str]], after: str = "") -> str:
    body = "\n".join(f"old = {old!r}; assert old in s, old\ns = s.replace(old, {new!r}, 1)" for old, new in edits)
    return render(PATCH_SH, COMMENT=comment, PROJECT=project, EDITS=body, AFTER=after)


