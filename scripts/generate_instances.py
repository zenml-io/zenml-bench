    rs = p["row_seed"]
    on_disk = [d for d in p["days"] if not (p["distractors"]["missing_file"] and d == p["days"][0])]
    for k, d in enumerate(on_disk):
        faulty = d == p["target"]
        fields, rows = b10_rows(p, d, rs + k, random.Random(rs + k).randint(30, 60), faulty, extra_column=p["extra"] if (faulty and fault == "new_column") else None)
